-- 17. PAYMENTS (created_at = เวลาอัปโหลดสลิป)
--   Auto-Slip Verification: verification_method = AUTO (ระบบตรวจเอง, verified_by = NULL = SYSTEM)
--                           หรือ MANUAL (ภาพไม่ชัด/อ่านเลขอ้างอิงไม่ได้ -> คิว Inspector Console ให้พนักงานตรวจ)
CREATE TABLE PAYMENTS (
    payment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id NUMBER NOT NULL,
    payment_method VARCHAR2(30) DEFAULT 'SLIP_TRANSFER' NOT NULL,
    amount NUMBER(10,2) NOT NULL,
    slip_url VARCHAR2(500),
    slip_reference VARCHAR2(50),          -- เลขอ้างอิงสลิป (slip_ref) กันใช้สลิปซ้ำ (UC-7)
    slip_mime_type VARCHAR2(50),          -- ประเภทไฟล์สลิปที่อัปโหลด (image/jpeg, image/png, image/webp)
    slip_file_size NUMBER,                -- ขนาดไฟล์สลิป (ไบต์)
    status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL, -- PENDING, VERIFIED, REJECTED
    verification_method VARCHAR2(10) DEFAULT 'MANUAL' NOT NULL, -- AUTO, MANUAL
    review_reason VARCHAR2(255),          -- เหตุผลที่ระบบส่งเข้าคิวให้พนักงานตรวจ (เช่น ภาพไม่ชัด)
    verified_by NUMBER,
    verified_at TIMESTAMP,
    rejection_reason VARCHAR2(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by NUMBER,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_by NUMBER,
    CONSTRAINT fk_pay_booking FOREIGN KEY (booking_id) REFERENCES BOOKINGS(booking_id),
    CONSTRAINT fk_pay_verifier FOREIGN KEY (verified_by) REFERENCES USERS(user_id)
);

