-- VARCHAR2(n) นับเป็น "ตัวอักษร" แทน "ไบต์" (ภาษาไทยใช้ 3 ไบต์ต่อตัวใน AL32UTF8 ถ้านับเป็นไบต์จะเก็บข้อความไทยได้แค่ 1/3)
ALTER SESSION SET NLS_LENGTH_SEMANTICS = CHAR;

-- Drop tables if they exist (in reverse order of dependencies)
BEGIN
   FOR c IN (SELECT table_name FROM user_tables WHERE table_name IN (
      'AUDIT_LOGS', 'NOTIFICATIONS', 'REFUND_REQUESTS', 'RECEIPTS', 'PAYMENTS',
      'FINES', 'EQUIPMENT_BORROWINGS', 'BOOKING_EQUIPMENT', 'BOOKING_STATUS_HISTORY',
      'BOOKINGS', 'EQUIPMENT', 'PROMOTIONS', 'PRICING_RATES', 'COURT_OPERATING_HOURS',
      'COURTS', 'SPORT_TYPES', 'USER_SESSIONS', 'USER_ROLES', 'USERS', 'MEMBER_TYPES', 'ROLES'
   )) LOOP
      EXECUTE IMMEDIATE 'DROP TABLE "' || c.table_name || '" CASCADE CONSTRAINTS PURGE';
   END LOOP;
END;
/

-- ผู้กระทำ (actor) ของ Transaction: backend ตั้ง CLIENT_IDENTIFIER = user_id ก่อนรันคำสั่ง
CREATE OR REPLACE FUNCTION f_current_actor RETURN NUMBER IS
BEGIN
   RETURN TO_NUMBER(SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'));
EXCEPTION
   WHEN VALUE_ERROR OR INVALID_NUMBER THEN RETURN NULL;
END;
/

