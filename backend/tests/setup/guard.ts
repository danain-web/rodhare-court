const url = process.env.DATABASE_URL || '';
if (process.env.NODE_ENV !== 'test' || !/@127\.0\.0\.1:\d+\//.test(url)) {
  throw new Error('เทสต์ต้องรันกับฐานข้อมูลทดสอบในเครื่องเท่านั้น (globalSetup) — ปฏิเสธการรันกับฐานข้อมูลจริง');
}
